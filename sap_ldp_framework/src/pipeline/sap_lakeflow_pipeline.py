# ── 1. Resolve and load the config ──────────────────────────────────────

_FNAME_RE = re.compile(
    rf"^{re.escape(PIPELINE_ID)}_{re.escape(ENVIRONMENT)}_(\d{{8}}_\d{{6}})_config\.json$")


def resolve_config_path():
    """The pipeline_config_versions row marked 'current' is authoritative:
    the registry writes the file first and marks it current second, so a
    newer file without a 'current' row is a failed registration. Falls
    back to the newest timestamped file if the table can't be read."""
    try:
        rows = spark.sql(
            f"""SELECT config_path FROM {CTRL}.pipeline_config_versions
                WHERE pipeline_id = :p AND environment = :e AND version_status = 'current'
                ORDER BY version_number DESC LIMIT 1""",
            args={"p": PIPELINE_ID, "e": ENVIRONMENT}).collect()
        if rows and rows[0]["config_path"]:
            return rows[0]["config_path"], "pipeline_config_versions (current)"
    except Exception as ex:
        log("CONFIG", f"Could not read {CTRL}.pipeline_config_versions: {ex}", "WARNING")

    folder = f"{CONFIG_OUT_DIR}/{PIPELINE_ID}"
    try:
        entries = dbutils.fs.ls(folder)
    except Exception as ex:
        raise FileNotFoundError(f"Could not list config folder '{folder}': {ex}")
    candidates = sorted((m.group(1), e.path) for e in entries if (m := _FNAME_RE.match(e.name)))
    if not candidates:
        raise FileNotFoundError(
            f"No config '{PIPELINE_ID}_{ENVIRONMENT}_<timestamp>_config.json' in {folder}. "
            f"Run the metadata loader first.")
    return candidates[-1][1], "newest file in config folder (fallback)"


config_path, config_origin = resolve_config_path()
config = json.loads(spark.read.text(config_path, wholetext=True).first()[0])

if config.get("pipeline_id") != PIPELINE_ID or config.get("environment") != ENVIRONMENT:
    raise ValueError(
        f"Config {config_path} is for {config.get('pipeline_id')}/{config.get('environment')}, "
        f"not {PIPELINE_ID}/{ENVIRONMENT}")

_open_shared_log(config.get("generated_at") or datetime.now().strftime("%Y%m%d_%H%M%S"))
log("CONFIG", f"pipeline_id={PIPELINE_ID} environment={ENVIRONMENT}")
log("CONFIG", f"Config v{config.get('version_number', '?')}: {config_path} (from {config_origin})")

