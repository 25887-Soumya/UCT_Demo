# ── 3. Bronze: Auto Loader over the SAP landing folders ──────────────────

BRONZE_TABLE_PROPERTIES = {
    "delta.feature.timestampNtz": "supported",
    "delta.columnMapping.mode":   "name",
    "delta.minReaderVersion":     "2",
    "delta.minWriterVersion":     "5",
}


def register_bronze(layer: dict):
    name   = layer["name"]
    source = layer.get("source") or {}
    if (layer.get("source_type") or "file") != "file" or source.get("type") != "autoloader":
        raise ValueError(f"Bronze '{name}': only SAP landing files (Auto Loader) are supported")

    target       = get_dlt_table_name(layer["target"]["table_name"])
    hints        = schema_to_hints(layer.get("schema"))
    clean_rules  = layer.get("clean_rules") or []
    expect_rules = layer.get("expect_rules") or []
    # Same path PipelineRegistry._clean_schema_locations() clears:
    # {base_volume}/schema/{layer_name}
    schema_root  = f"{BASE_VOLUME}/schema/{name}"

    raw_paths = [p.strip() for p in (source.get("path") or "").split(",") if p.strip()]
    if not raw_paths:
        raise ValueError(f"Bronze '{name}' has no source path")
    parent     = _common_parent(raw_paths)
    load_paths = [parent] if parent else raw_paths
    recursive  = bool(parent)

    def read(path: str, schema_location: str):
        reader = (
            spark.readStream.format("cloudFiles")
            .option("cloudFiles.format", source.get("format") or "parquet")
            .option("cloudFiles.schemaLocation", schema_location)
            .option("cloudFiles.schemaEvolutionMode", "rescue")
            .option("cloudFiles.cleanSource", "MOVE")
            .option("cloudFiles.cleanSource.moveDestination", _archive_dir(path))
            .option("cloudFiles.cleanSource.retentionDuration", ARCHIVE_AFTER)
        )
        if recursive:
            reader = reader.option("recursiveFileLookup", "true")
        if hints:
            reader = reader.option("cloudFiles.schemaHints", hints)
        df = normalize_system_columns(reader.load(path))
        df = df.select([f.name for f in df.schema.fields
                        if type(f.dataType).__name__ in SUPPORTED_TYPES])
        df = apply_mappings(df, clean_rules)
        return df.withColumn("_ingestion_time", current_timestamp())

    if len(load_paths) == 1:
        def _bronze():
            return read(load_paths[0], schema_root)

        dp.table(name=target, comment=f"Bronze — {name}",
                 table_properties=BRONZE_TABLE_PROPERTIES)(with_expectations(_bronze, expect_rules))
        log("BRONZE", f"{target} ← {load_paths[0]}" + (" (recursive)" if recursive else ""))
        return

    # Disjoint paths: one append flow per path into one streaming table.
    # Each flow needs its own schema location (two streams must not share
    # one); both sit under schema_root, so the registry still clears them.
    # Expectations go on the table, since flows don't take them.
    b = _split_expectations(expect_rules)
    dp.create_streaming_table(
        name=target, comment=f"Bronze — {name}",
        table_properties=BRONZE_TABLE_PROPERTIES,
        expect_all=b["warn"] or None,
        expect_all_or_drop=b["drop"] or None,
        expect_all_or_fail=b["fail"] or None,
    )
    for i, path in enumerate(load_paths):
        def _flow(path=path, i=i):   # default args bind this iteration's values
            return read(path, f"{schema_root}/flow_{i}")
        dp.append_flow(target=target, name=f"{target.split('.')[-1]}_flow_{i}")(_flow)
    log("BRONZE", f"{target} ← {len(load_paths)} paths (one append flow each)")

