# ── 4. Silver: full / delta / scd1 / scd2 ────────────────────────────────

SILVER_TABLE_PROPERTIES = {"delta.feature.timestampNtz": "supported"}
# Columns that change on every load; SCD2 must not open a new version
# when only these differ.
SCD2_UNTRACKED_COLUMNS = ["_ingestion_time", "_rescued_data"]

BRONZE_BY_TARGET = {
    l["target"]["table_name"]: l for l in config["layers"] if l.get("dlt_mode") == "bronze"
}


def _silver_source(layer: dict) -> str:
    src = (layer.get("source") or {}).get("table_name")
    if not src:
        raise KeyError(f"Silver '{layer['name']}': source has no table_name — "
                       f"regenerate the config with the metadata loader.")
    return src


def _canonical(c):
    return c.lower() if c and c.lower() in SYSTEM_COL_CASTS else c


def _sequence_by(layer: dict, source_table: str):
    """__timestamp alone can tie for two changes to the same key. When the
    SAP metadata has a sequence column, order by (timestamp, sequence)."""
    wm = _canonical(layer.get("sequence_by"))
    if not wm:
        raise KeyError(f"Silver '{layer['name']}': no sequence_by in config")
    seq = _canonical(BRONZE_BY_TARGET.get(source_table, {}).get("sequence_col"))
    if seq and seq != wm:
        return struct(col(wm), col(seq)), f"struct({wm}, {seq})"
    return col(wm), wm


def register_silver_snapshot(layer: dict):
    """load_type=full: streaming mirror of bronze, every row kept as-is."""
    source_table = _silver_source(layer)
    target       = get_dlt_table_name(layer["target"]["table_name"])
    mappings     = (layer.get("transformations") or {}).get("mappings", [])

    def _silver():
        return apply_mappings(spark.readStream.table(source_table), mappings)

    dp.table(name=target, comment=f"Silver full — {layer['name']}",
             table_properties=SILVER_TABLE_PROPERTIES)(_silver)
    log("SILVER", f"{target} ← {source_table} (full mirror)")


def register_silver_delta(layer: dict):
    """load_type=delta: append-only incremental feed, no keys."""
    source_table = _silver_source(layer)
    target       = get_dlt_table_name(layer["target"]["table_name"])
    mappings     = (layer.get("transformations") or {}).get("mappings", [])
    wm           = _canonical(layer.get("sequence_by"))

    def _silver():
        df = spark.readStream.table(source_table)
        if wm:
            df = df.filter(col(wm).isNotNull())
        return apply_mappings(df, mappings)

    dp.table(name=target, comment=f"Silver delta — {layer['name']}",
             table_properties=SILVER_TABLE_PROPERTIES)(_silver)
    log("SILVER", f"{target} ← {source_table} (delta append)")


def register_silver_cdc(layer: dict, scd_type: int):
    """load_type=scd1 (upsert, latest row per key) or scd2 (full history)."""
    source_table = _silver_source(layer)
    target       = get_dlt_table_name(layer["target"]["table_name"])
    keys         = layer.get("keys") or []
    mappings     = (layer.get("transformations") or {}).get("mappings", [])
    delete_cond  = layer.get("delete_condition")
    if not keys:
        raise KeyError(f"Silver '{layer['name']}': SCD{scd_type} needs keys — the SAP "
                       f"metadata for this table has no primary key.")
    seq_col, seq_desc = _sequence_by(layer, source_table)

    cdc_source = source_table
    if mappings:
        # create_auto_cdc_flow takes a source NAME, so transforms go in a view.
        cdc_source = f"{target.split('.')[-1]}_pre_cdc"

        def _pre_cdc():
            return apply_mappings(spark.readStream.table(source_table), mappings)

        dp.temporary_view(name=cdc_source, comment=f"Pre-CDC transforms — {layer['name']}")(_pre_cdc)

    dp.create_streaming_table(name=target, comment=f"Silver SCD{scd_type} — {layer['name']}",
                              table_properties=SILVER_TABLE_PROPERTIES)
    kwargs = dict(target=target, source=cdc_source, keys=keys,
                  sequence_by=seq_col, stored_as_scd_type=scd_type)
    if delete_cond:
        kwargs["apply_as_deletes"] = expr(delete_cond)
    if scd_type == 2:
        kwargs["track_history_except_column_list"] = SCD2_UNTRACKED_COLUMNS
    dp.create_auto_cdc_flow(**kwargs)
    log("SILVER", f"{target} ← {source_table} (SCD{scd_type}, keys={keys}, "
                  f"sequence_by={seq_desc}, deletes={delete_cond or 'none'})")

