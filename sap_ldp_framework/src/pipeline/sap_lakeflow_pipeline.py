# Databricks notebook source
# ════════════════════════════════════════════════════════════════════════
# SAP S/4HANA (Datasphere replication flow) → Bronze → Silver
# Config-driven Lakeflow Declarative Pipeline
#
# Gold is NOT built here: gold tables join and transform several silver
# tables and need MERGE / multi-step SQL, so they run in the separate
# sap_gold notebook (next job task). Gold layers (layer_type=spark) in the
# config are ignored by this pipeline.
#
# Pipeline configuration (Settings → Advanced → Configuration):
#   pipeline_id      REQUIRED  pipeline_name from pipeline_table_config
#   environment      REQUIRED  dev | qa | prod
#   ctrl_schema      optional  control-table schema written by the registry
#                              (default rgaplxdatabricks.uct_demo)
#   base_volume      optional  framework volume holding configs/, schema/, logs/
#   config_out_dir   optional  default {base_volume}/configs
#   archive_after    optional  cleanSource wait before moving files (default "7 days")
#
# Layers, as generated by pipeline_register:
#   bronze  layer_type=dlt   dlt_mode=bronze   streaming table via Auto Loader
#   silver  layer_type=dlt   dlt_mode=snapshot streaming mirror   (load_type full)
#                            dlt_mode=delta    streaming append   (load_type delta)
#                            dlt_mode=upsert   auto CDC, SCD1     (load_type scd1)
#                            dlt_mode=history  auto CDC, SCD2     (load_type scd2)
#   gold    layer_type=spark                   skipped — built by the sap_gold notebook
#
# This file only DEFINES datasets. DDL/DML is rejected inside a pipeline
# source file, so gold, run history and reconciliation are written by
# notebooks that run after this pipeline in the same job.
# ════════════════════════════════════════════════════════════════════════

