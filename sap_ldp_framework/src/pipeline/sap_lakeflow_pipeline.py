# ── 2. Helpers ──────────────────────────────────────────────────────────

DDL_TYPE_MAP = {
    "string": "STRING", "long": "BIGINT", "bigint": "BIGINT", "integer": "INT",
    "int": "INT", "double": "DOUBLE", "float": "FLOAT", "boolean": "BOOLEAN",
    "timestamp": "TIMESTAMP", "timestamp_ntz": "TIMESTAMP_NTZ", "date": "DATE",
    "binary": "BINARY",
}
_DECIMAL_RE = re.compile(r"^decimal\(\s*\d+\s*,\s*\d+\s*\)$", re.IGNORECASE)
_PLAIN_IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# Types Delta can store. Anything else Auto Loader produces is dropped.
SUPPORTED_TYPES = {
    "StringType", "LongType", "IntegerType", "ShortType", "ByteType",
    "DoubleType", "FloatType", "DecimalType", "BooleanType", "DateType",
    "TimestampType", "TimestampNTZType", "BinaryType", "NullType",
}

# Datasphere system columns. Files for the same table have been seen with
# different casing (__timestamp vs __Timestamp); with column mapping on,
# those would become two physical columns, so every variant is collapsed
# onto one lowercase name with one type right after the read.
SYSTEM_COL_CASTS = {
    "__timestamp":       "timestamp_ntz",
    "__operation_type":  "string",
    "__sequence_number": "decimal(20,0)",
}


def _ddl_type(t: str):
    t = (t or "").strip().lower()
    if _DECIMAL_RE.match(t):
        return t.upper().replace(" ", "")
    return DDL_TYPE_MAP.get(t)


def schema_to_hints(schema_dict) -> str:
    """Config schema → cloudFiles.schemaHints. Columns with unsupported
    types are left to parquet inference. SAP names such as /BIC/FIELD are
    backtick-quoted."""
    parts = []
    for f in (schema_dict or {}).get("fields", []):
        typ = _ddl_type(f.get("type"))
        if typ is None:
            log("SCHEMA_HINTS", f"Skipping {f.get('name')} ({f.get('type')}): unsupported type", "WARNING")
            continue
        name = f["name"] if _PLAIN_IDENT_RE.match(f["name"]) else f"`{f['name']}`"
        parts.append(f"{name} {typ}")
    return ", ".join(parts)


def normalize_system_columns(df):
    for canonical, cast_type in SYSTEM_COL_CASTS.items():
        variants = [f.name for f in df.schema.fields if f.name.lower() == canonical]
        if not variants:
            continue
        if variants == [canonical]:
            df = df.withColumn(canonical, col(canonical).cast(cast_type))
            continue
        # Other casing(s), possibly several in one micro-batch: coalesce
        # them into the canonical column instead of renaming (a rename
        # would collide).
        merged = coalesce(*[col(v).cast(cast_type) for v in variants])
        df = df.drop(*variants).withColumn(canonical, merged)
    return df


def get_dlt_table_name(full_name: str) -> str:
    """catalog.schema.table → schema.table (the pipeline's catalog is implied)."""
    parts = full_name.split(".")
    return f"{parts[1]}.{parts[2]}" if len(parts) == 3 else full_name


def apply_mappings(df, mappings):
    for m in mappings or []:
        df = df.withColumn(m["target_column"], expr(m["transform_rule"]))
    return df


def _split_expectations(rules):
    buckets = {"warn": {}, "drop": {}, "fail": {}}
    for r in rules or []:
        action = (r.get("action") or "warn").lower()
        if action not in buckets:
            raise ValueError(f"Expectation '{r.get('name')}': action must be warn|drop|fail")
        buckets[action][r["name"]] = r["constraint"]
    return buckets


def with_expectations(fn, rules):
    """Wraps the dataset function BEFORE dp.table/materialized_view is
    applied — expectations added after registration are silently lost."""
    b = _split_expectations(rules)
    if b["warn"]:
        fn = dp.expect_all(b["warn"])(fn)
    if b["drop"]:
        fn = dp.expect_all_or_drop(b["drop"])(fn)
    if b["fail"]:
        fn = dp.expect_all_or_fail(b["fail"])(fn)
    return fn


def _common_parent(paths):
    """initial/ and delta/ folders of one table share a parent. A streaming
    read accepts only one path, so those are read as one recursive stream."""
    norm = [p.rstrip("/") for p in paths if p.strip()]
    if len(norm) < 2:
        return None
    parents = {p.rsplit("/", 1)[0] for p in norm}
    return next(iter(parents)) + "/" if len(parents) == 1 else None


def _archive_dir(path: str) -> str:
    """cleanSource destination OUTSIDE the table folder. An archive inside a
    recursively-scanned folder would be picked up again as new files."""
    parts = path.rstrip("/").split("/")
    if parts[-1] in ("initial", "delta"):
        table_seg, base = parts[-2], "/".join(parts[:-2])
    else:
        table_seg, base = parts[-1], "/".join(parts[:-1])
    return f"{base}/_archive/{table_seg}/"

