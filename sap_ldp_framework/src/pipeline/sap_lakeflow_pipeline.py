# ── 5. Register bronze and silver layers ─────────────────────────────────────

SILVER_ROUTES = {
    "bronze":   register_bronze,
    "snapshot": register_silver_snapshot,
    "full":     register_silver_snapshot,   # configs generated before the dlt_mode fix
    "delta":    register_silver_delta,
    "upsert":   lambda l: register_silver_cdc(l, 1),
    "history":  lambda l: register_silver_cdc(l, 2),
}

layers = [l for l in config["layers"] if l.get("layer_type") == "dlt"]
n_gold = sum(1 for l in config["layers"] if l.get("layer_type") == "spark")
log("REGISTER", f"Registering {len(layers)} bronze/silver layer(s); "
                f"{n_gold} gold layer(s) left to the sap_gold notebook")

failures = []
for layer in layers:
    try:
        if layer.get("dlt_mode") == "bronze_join":
            log("REGISTER", f"Skipping bronze_join layer '{layer['name']}' (not used for SAP)")
        elif layer.get("dlt_mode") in SILVER_ROUTES:
            SILVER_ROUTES[layer["dlt_mode"]](layer)
        else:
            raise ValueError(f"unknown dlt_mode '{layer.get('dlt_mode')}'")
    except Exception as exc:
        reason = " ".join(str(exc).split())[:200]
        failures.append(f"{layer.get('name', '?')}: {reason}")
        log("REGISTER", f"FAILED {layer.get('name', '?')}: {exc}", "ERROR")

if failures:
    # One line: the run page truncates the error at the first newline.
    raise RuntimeError(f"{len(failures)} layer(s) failed to register — " + "  |  ".join(failures))

log("REGISTER", f"All {len(layers)} layer(s) registered. Log: {_LOG_FILE_PATH}")
