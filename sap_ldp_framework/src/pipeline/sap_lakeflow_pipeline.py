# ── 0. Pipeline configuration + logging ─────────────────────────────────

def _conf(key: str, default: str = "", required: bool = False) -> str:
    val = (spark.conf.get(key, default) or "").strip()
    if required and not val:
        raise ValueError(
            f"Pipeline configuration key '{key}' is required. Set it under "
            f"Pipeline settings → Advanced → Configuration.")
    return val


PIPELINE_ID    = _conf("pipeline_id", required=True)
ENVIRONMENT    = _conf("environment", required=True).lower()
CTRL           = _conf("ctrl_schema", "rgaplxdatabricks.uct_demo")
BASE_VOLUME    = _conf("base_volume", "/Volumes/rgaplxdatabricks/temp_source/source_files").rstrip("/")
CONFIG_OUT_DIR = _conf("config_out_dir", f"{BASE_VOLUME}/configs").rstrip("/")
ARCHIVE_AFTER  = _conf("archive_after", "7 days")
LOG_DIR        = f"{BASE_VOLUME}/logs"

if ENVIRONMENT not in ("dev", "qa", "prod"):
    raise ValueError(f"environment must be dev|qa|prod — got '{ENVIRONMENT}'")

COMPONENT      = "LAKEFLOW"
_LOG_LINES     = []
_LOG_FILE_PATH = None


def _flush_log():
    # Volumes are FUSE-mounted and don't support append mode ("a" needs a
    # seek), so the whole file is rewritten from the in-memory buffer.
    if not _LOG_FILE_PATH:
        return
    try:
        with open(_LOG_FILE_PATH, "w") as f:
            f.write("\n".join(_LOG_LINES) + "\n")
    except Exception as ex:
        print(f"WARNING: could not write log file {_LOG_FILE_PATH}: {ex}")


def log(stage: str, message: str, level: str = "INFO"):
    line = f"{datetime.now():%Y-%m-%d %H:%M:%S} [{level}] [{COMPONENT}] [{stage}] {message}"
    print(line)
    _LOG_LINES.append(line)
    _flush_log()


def _open_shared_log(generated_at: str):
    """The log file is named after the config's generated_at, so this
    pipeline and pipeline_audit write to the same file. Lines already in
    the file are kept, not overwritten."""
    global _LOG_FILE_PATH
    path = f"{LOG_DIR}/{PIPELINE_ID}_{ENVIRONMENT}_{generated_at}.log"
    try:
        os.makedirs(LOG_DIR, exist_ok=True)
        if os.path.exists(path):
            with open(path) as f:
                existing = f.read().rstrip("\n")
            if existing:
                _LOG_LINES[:0] = existing.split("\n")
        _LOG_FILE_PATH = path
        _flush_log()
    except Exception as ex:
        print(f"WARNING: could not open log file {path}: {ex}")

